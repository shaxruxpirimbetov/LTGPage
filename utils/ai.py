from google import genai
from decouple import config

api_key = config('GEMINI_API_KEY')
client = genai.Client(api_key=api_key)


def generate_html(prompt):
    system_prompt = f"""Ты — генератор HTML-страниц. Пользователь описал, какую страницу или элемент он хочет получить, а ты должен сгенерировать полностью готовый, самодостаточный HTML-код.

    Запрос пользователя: "{prompt}"

    Правила:
    1. Возвращай ТОЛЬКО чистый HTML-код — без markdown-разметки (без ```html и ```), без пояснений до или после кода.
    2. Весь CSS должен быть внутри <style> в <head>, весь JS (если нужен) — внутри <script> перед закрывающим </body>. Не используй внешние файлы.
    3. Код должен быть валидным, самодостаточным и сразу открываться в браузере без дополнительных зависимостей.
    4. Используй современный, чистый и адаптивный (responsive) дизайн, если пользователь не указал иное.
    5. Если запрос пользователя неясен или слишком короткий — сам придумай разумное содержимое и оформление, не задавай уточняющих вопросов.
    6. Не добавляй комментарии в код, если явно не попросили.
    7. Ответ должен начинаться сразу с <!DOCTYPE html> и заканчиваться </html>.
    """

    res = client.models.generate_content(
        model="gemini-3.5-flash",
        contents=[system_prompt]
    )
    return res.text